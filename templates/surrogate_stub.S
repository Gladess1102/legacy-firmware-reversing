; surrogate_stub.S — DSP56300 替身桩模板（Motorola DSP56004/56300 24-bit 架构）
;
; 用途：把从固件中剥离的 overlay 模块放到 PC 端 JIT 仿真器（xemu-project/dsp56300）
; 上独立执行。不做完整内核逆向——只对模块的"对外调用点"手写极简桩，
; 让被测模块毫秒级跑通主流程，然后观测它的内存写入/外设位流。
;
; 汇编：dsp56300-asm stubs.s -o stubs.lod -f lod
; 加载：LOD 里的 "P <addr> <word>" 行按绝对地址覆盖进 PRAM。
;
; 实战来源：Sharp MP-B300 CID26 tuner 模块（除法桩 + 消息记录桩 + GPIO 假外设）。

; ── 1. 除法桩 ──────────────────────────────────────────────────────────
; DSP56004 无硬件除法指令，固件用 "rep #24 + div" 惯用法。
; 桩必须与原实现语义一致：a = a / y0（商在 a0），并保持 a1/a2 状态约定。
; 先反汇编原除法函数抄语义，不要自己发明。
  org p:$6A4C
  rep #24
  div y0,a
  rts

; 同一固件里常见多个变体（不同舍入/符号约定），逐个对号入座：
  org p:$6AC3
  rep #24
  div y0,a
  rts

; ── 2. 消息记录桩 ──────────────────────────────────────────────────────
; 对"发往常驻内核、但内核本体无法加载"的消息调用点，用记录桩截获：
; 把栈上参数快照进一块 X 内存环形缓冲，仿真结束后 dump 分析。
; 约定：x:$E7FE = 写指针（由仿真器宿主初始化），缓冲区从 x:$E000 起。
  org p:$68FD
  move x:$00E7FE,r0
  nop
  move #-1,n7
  nop
  move y:(r7+n7),a
  move a,x:(r0)+
  move #-2,n7
  nop
  move y:(r7+n7),a
  move a,x:(r0)+
  move #-3,n7
  nop
  move y:(r7+n7),a
  move a,x:(r0)+
  move r7,a
  move a,x:(r0)+
  rts

; ── 3. rts 毯（安全网）────────────────────────────────────────────────
; 把桩未覆盖的全部内核地址空间预填 rts（word 0x00000C）：
; 任何漏网调用安全返回，被测模块流程必达终点。
; 注意：不要覆盖被测模块本体与其数据段！
; 由宿主脚本在加载 LOD 之前执行（伪码）：
;   for addr in KERNEL_MIN..KERNEL_MAX: pram[addr] = 0x00000C
;   for line in stubs.lod: pram[line.addr] = line.word

; ── 4. 已知暗坑（血泪教训，写桩前必读）──────────────────────────────
; a) do/rep 硬件循环：绝对不要 NOP 掉硬件循环体内的条件跳转——
;    do a0 的 LC 计数器下溢会变成 2^24 次死循环（真机表现为白屏假死）。
;    要改判定，把跳转目标改成"循环出口地址"，而不是 NOP。
; b) 绝对寻址桩的 JIT 缓存：在部分宿主实现里，运行中改写 x 内存
;    （如假外设的 DATA_IN 回环）对 JIT 块不可见——外设必须走
;    Callback 内存区（read_fn/write_fn），不要用主循环轮询回写。
; c) 位序：3-wire 外设的采样沿（上升/下降）与位序（MSB/LSB first）
;    必须先录原始 GPIO 波形肉眼确认，不要照抄 datasheet 想当然——
;    本案例中固件实际是"下降沿采样、跨 NRW 窗口累计"，与笔记相反。
; d) overlay 加载基址：模块内 jsr 目标是绝对地址。用
;    "跳转目标必须落在函数序言（movec ssh,y:(r7)+）上"这一约束
;    暴力求解加载基址（枚举候选基址取命中最多者），再用调用热度交叉验证。
